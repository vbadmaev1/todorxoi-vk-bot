# =============================================================================
# ТИРЕ
# =============================================================================
#
# Тире, набранное в исходном тексте (— или –), до таблиц не доходит: в них
# его нет, и в картинку уезжал пустой квадрат. Заменяем его на U+FE31 —
# «презентационную форму вертикального тире». Название обманчиво: в этом
# шрифте знак нарисован горизонтальной чертой, как и все буквы, а
# вертикальным становится после поворота строки — ровно то, что нужно.
#
# Отделяем пробелами с обеих сторон: без них тире прилипает к соседнему
# слову и читается как часть стержня.
#
# Дефис внутри слова сюда не попадает — он остаётся границей суффикса и
# ниже превращается в узкий неразрывный пробел.
VERTICAL_DASH = "\uFE31"

# длинное, короткое, цифровое тире, горизонтальная черта, минус — и
# отдельно стоящий дефис, окружённый пробелами: его тоже считаем тире
_DASH_RE = re.compile(r"[ \t]*(?:[\u2012-\u2015\u2212]|(?<=\s)-(?=\s))[ \t]*")


def _dashes_to_vertical(text):
    return _DASH_RE.sub(f" {VERTICAL_DASH} ", text)


def translit_to_todo(text):
    """Транслитерация проекта -> юникодный текст тодо бичиг.

    Вход приводится к нижнему регистру: в тодо бичиг прописных букв нет,
    а промежуточная ASCII-схема использует регистр как значащий (O = ö,
    U = ü, C = č, S = š, G = γ). Без этого заглавная буква в начале
    предложения просто не конвертировалась бы («Xalimaq» -> «Xᠠᠯᡅᡏᠠᡎ»).

    Переводы строк обрабатываются отдельно: в исходной JS-таблице "\\n"
    отображается в литерал "<br>" (это имело смысл для веб-страницы, но не
    здесь — иначе «<br>» так и уедет в картинку). Поэтому режем текст по
    строкам, конвертируем каждую и склеиваем обратно через "\\n".
    """
    lines = _dashes_to_vertical(text).split("\n")
    return "\n".join(_rom_to_todo(translit_to_rom(line.lower())) for line in lines)


# Те же три записи ǰ, но в готовом юникоде: для текста, который пришёл не
# через translit_to_todo. Модель распознавания фото обучена на разметке,
# где ǰ везде была ᡓ, и так и читает.
_TODO_JI = re.compile("ᡓ(?=ᡅ)")
_TODO_J_INITIAL_BACK = re.compile(r"(?<![\u180b-\u180f\u1820-\u18aa])ᡓ(?=[ᠠᡆᡇ])")


def normalize_j(todo_text):
    """ᡓ -> ᠴ перед ᡅ и ᡓ -> ᡚ в начале слова перед задней гласной."""
    return _TODO_J_INITIAL_BACK.sub("ᡚ", _TODO_JI.sub("ᠴ", todo_text))


# Дифтонг внутри слова: гласная + i перед согласной пишется через y —
# xoyišidu, bayixu, züyil, üzügiyin. Так в корпусе почти без исключений
# (a: 63 781 против 15, o: 10 054 против 136; без y — заимствования и
# опечатки). В конце слова, наоборот, без y: dalai, ügei, toloγoi (55 107
# против 95) — его не трогаем; перед гласной корпус пишет и так, и так.
# Модель распознавания y иногда пропускает (xoišidu, baixu): на рисунке
# дифтонга буквы y почти не видно.
_TODO_VOWELS = "ᠠᡄᡅᡆᡇᡈᡉ"
_TODO_CONSONANTS = "".join(
    chr(c) for c in range(0x1820, 0x18AB) if chr(c) not in _TODO_VOWELS + "ᡃ"
)
_TODO_DIPHTHONG_I = re.compile(f"(?<=[{_TODO_VOWELS}ᡃ])ᡅ(?=[{_TODO_CONSONANTS}])")
# Родительный и винительный падеж, написанные отдельно (через узкий
# пробел), — yin и yigi после любой основы: tere-yigi, mani-yigi,
# öün-yigi, bičiq-yigi (yigi 2740 против igi 2, yin 213 против in 18).
# Модель распознавания читает их как in и igi: начальная y на рисунке
# почти сливается с i. С y и кириллица верная: üge yin -> үгин, а не «үг ин».
_TODO_CASE_SUFFIX = re.compile(r"(?<![ᠠ-ᢪ])(?=ᡅ(?:ᠨ|ᡎᡅ)(?![ᠠ-ᢪ]))")


def normalize_yi(todo_text):
    """Пропущенная y: гласная + ᡅ перед согласной -> гласная + ᡕᡅ
    (xoišidu -> xoyišidu); отдельное окончание in, igi -> yin, yigi."""
    return _TODO_CASE_SUFFIX.sub("ᡕ", _TODO_DIPHTHONG_I.sub("ᡕᡅ", todo_text))


# Знак долготы стоит только после гласной: после согласной его нет ни в
# корпусе, ни в разметке настоящих рукописей, ни в синтетике. В синьцзянских
# учебниках долгота нарисована кружком сбоку от согласной перед гласной, и
# модель так и ставит её: luq:a, dar:a вместо luγā, darā. Переносим за
# гласную; если у гласной долгота уже есть (caq:ā) или гласной нет (čamč:),
# лишний знак просто убираем.
_TODO_LONG_AFTER_CONSONANT = re.compile(f"(?<=[{_TODO_CONSONANTS}])ᡃ([{_TODO_VOWELS}])(ᡃ?)")
_TODO_STRAY_LONG = re.compile(f"(?<=[{_TODO_CONSONANTS}])ᡃ")
# Окончание -iia: его нет ни в корпусе, ни в разметке, а -iyin — 24 тыс.
# раз. Модель путает конечную n с конечной a (у обеих хвост влево) и
# читает nutugiyin как nutugiia.
_TODO_IIA = re.compile(r"ᡅᡅᠠ(?![ᠠ-ᢪ])")
# «?!» в конце строки стихотворения модель читает как i и один из знаков: büi?! -> büii?. Слов на -ii в
# корпусе 22 формы на 1.3 млн употреблений (48 раз).
_TODO_II_PUNCT = re.compile("ᡅᡅ(?=[︕︖])")
# Конечная n после согласной — та же путаница n/a: borotaln вместо borotala.
# В корпусе такого конца почти нет (l, γ, x, d, b, m, r, s: 0–22 раза против
# тысяч с a), это мусор вроде töüyigittn. Кроме š (nemešn 40 против 2), y
# (в рукописях yin сокращают до yn: zorigiyn), n (удвоенная nn — отдельная
# ошибка), ng и w.
_TODO_FINAL_N = re.compile(
    "(?<=[%s])ᠨ(?![\u180b-\u180f\u1820-\u18aa])" % re.sub("[ᠨᠱᡕᡊᡖ]", "", _TODO_CONSONANTS)
)

# После круглых b и p в части шрифтов o и ü нарисованы одинаково, и модель
# путает их: bürotaln вместо borotala. Выбираем по сингармонизму — по
# остальным гласным слова (i нейтральна): задних больше — o, передних — ü.
# По корпусу так верно в 99.5% случаев (45 980 против 215: заимствования
# вроде rebolüce). Если других гласных поровну или нет (bolǰi, bolbo, büli),
# оставляем то, что прочитала модель: в корпусе там o 15 301 раз, ü — 1 114,
# так что выбор по умолчанию в любую сторону ломал бы частые слова.
_TODO_ROUND_O_U = re.compile("[ᡋᡌ][\u180b-\u180f]?([ᡆᡉ])")
_TODO_LETTER_RUN = re.compile("[\u180b-\u180f\u1820-\u18aa]+")


def _round_vowel_harmony(match):
    word = match.group()
    spots = {m.start(1) for m in _TODO_ROUND_O_U.finditer(word)}
    if not spots:
        return word
    rest = [ch for i, ch in enumerate(word) if i not in spots]
    back = sum(ch in "ᠠᡆᡇ" for ch in rest)
    front = sum(ch in "ᡄᡈᡉ" for ch in rest)
    if back == front:
        return word
    vowel = "ᡆ" if back > front else "ᡉ"
    return "".join(vowel if i in spots else ch for i, ch in enumerate(word))


def fix_misreads(todo_text):
    """Ошибки чтения, которых в правильном тексте не бывает: долгота после
    согласной (dar:a -> darā), окончание -iia (nutugiia -> nutugiyin),
    конечная n после согласной (borotaln -> borotala), o/ü после b и p
    против сингармонизма (bürotala -> borotala)."""
    text = _TODO_LONG_AFTER_CONSONANT.sub(r"\1ᡃ", todo_text)
    text = _TODO_IIA.sub("ᡅᡕᡅᠨ", _TODO_STRAY_LONG.sub("", text))
    text = _TODO_FINAL_N.sub("ᠠ", _TODO_II_PUNCT.sub("ᡅ", text))
    return _TODO_LETTER_RUN.sub(_round_vowel_harmony, text)


def normalize_ocr(todo_text):
    """Всё, чем распознанный текст приводится к норме письма: ǰ, пропущенная
    y, ошибки чтения."""
    return normalize_yi(fix_misreads(normalize_j(todo_text)))


def todo_to_translit(todo_text):
    """Юникодный текст тодо бичиг -> транслитерация проекта.

    Переводы строк, как и в обратную сторону, обрабатываются построчно —
    чтобы "\\n" не превратился в литерал "<br>"."""
    out = []
    for line in todo_text.split("\n"):
        rom = _todo_to_rom(line)
        out.append(rom_to_translit(rom, word_for_harmony=rom))
    return "\n".join(out)


