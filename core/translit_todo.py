# Служебный символ для x/k: см. комментарий в _TRANSLIT_TO_ROM_MULTI.
# Нужен любой знак, которого заведомо нет в тексте и который не образует
# пары с соседями в таблице диграфов.
_H_MARK = "\x01"

# Второй служебный символ — для k перед задними гласными (а/о/у).
#
# В тодо бичиг это разные буквы: ᡍ (U+184D, TODO QA) — задний ряд, ᡗ
# (U+1857, TODO KA) — передний. Обычно они в дополнительном распределении:
# x идёт с задними гласными, k с передними, и обе спокойно писались через
# ᡍ. Но в заимствованиях k попадает перед задней гласной — кару, karou, —
# и тогда ᡍ прочтётся как q. Нужна явная ᡗ: ᡗᠠᠷᡆᡇ, а не ᡍᠠᠷᡆᡇ.
# В словаре таких слов 219 из 25 664.
_K_MARK = "\x02"

# Задние гласные на этом шаге уже приведены к ASCII: a, o, u. Передние
# огублённые стали заглавными O/U, так что строчные [aou] — ровно задний ряд.
_K_BEFORE_BACK = re.compile(r"k(?=[aou])")

# У ǰ в тодо бичиг три записи, по месту в слове:
#   ǰi (и ǰī)                      -> ᠴ (U+1834): ǰi -> ᠴᡅ, как či -> ᡔᡅ;
#   в начале слова перед a, o, u   -> ᡚ (U+185A), форма с петлёй: ᡚᠠᡊᡎᠠᠷ;
#   во всех остальных позициях     -> ᡓ (U+1853).
# Вторую форму подсказали правила семейства Clear Script, собранные по
# словарю: начальная ǰ перед задней гласной там всегда пишется отдельным
# начертанием (14 из 14 слов), перед i, e, ö и внутри слова — обычным.
#
# ᠴ — та же буква, что у z, поэтому для ǰi нужен служебный символ: голое
# "z" после d схлопнулось бы в таблице диграфов в ᡜ (dz).
_JI_MARK = "\x03"
# начало слова: перед ǰ нет буквы; ":" — это уже вынесенная долгота
# предыдущей гласной (āǰa -> "a:ǰa"), значит, ǰ стоит внутри слова
_J_INITIAL_BACK = re.compile(r"(?<![\w:])ǰ(?=[aou])")

_FRONT_VOWELS = {"ᡄ", "ᡅ", "ᡈ", "ᡉ"}
_BACK_VOWELS = {"ᠠ", "ᡆ", "ᡇ"}


def _rom_to_todo(rom_text):
    """Дословный перенос romToTodo(...) из JS."""
    for key, val in _REPLACEMENTS.items():
        rom_text = rom_text.replace(key, val)
    todo_text = "".join(_CHAR_ROM_TO_TODO.get(ch, ch) for ch in rom_text)
    todo_text = todo_text.replace("ny", "N")  # финальная правка, как в JS
    return todo_text


def _todo_to_rom(todo_text):
    """Дословный перенос todoToRom(...) из JS (с контекстными правилами)."""
    out = []
    n = len(todo_text)
    for i, ch in enumerate(todo_text):
        next_ch = todo_text[i + 1] if i + 1 < n else ""
        if ch == "ᡍ":  # h / k / x, зависит от следующей гласной
            if next_ch in _FRONT_VOWELS:
                out.append("k")
            elif next_ch in _BACK_VOWELS:
                out.append("x")
            else:
                out.append("h")
            continue
        if ch == "ᡎ":  # g / G(=γ) / q, зависит от следующей гласной
            if next_ch in _FRONT_VOWELS:
                out.append("g")
            elif next_ch in _BACK_VOWELS:
                out.append("G")
            else:
                out.append("q")
            continue
        if ch == "ᠴ" and next_ch == "ᡅ":
            # Обратная сторона правила ǰi -> ᠴᡅ: ᠴ перед i — это ǰ, в
            # остальных местах — z. В словаре ǰi — около 2000 слов, zi — 55.
            # Решаем здесь, а не на латинице: там ᡑᠴ и ᡜ оба дают "dz".
            out.append("j")
            continue
        if ch in _SPECIAL_TODO_TO_ROM:
            out.append(_SPECIAL_TODO_TO_ROM[ch])
            continue
        out.append(_CHAR_TODO_TO_ROM.get(ch, ch))
    return "".join(out)


