# долгие гласные: у JS долгота — отдельный символ ":", у нас — макрон на
# базовой гласной. "O:" / "U:" — способ показать долгий ö/ü через ASCII-схему
# JS (ö уже сама по себе "O", ü — "U", ":" добавляет долготу поверх любой
# предыдущей гласной).
_TRANSLIT_TO_ROM_MULTI = [
    ("ā", "a:"), ("ē", "e:"), ("ī", "i:"), ("ō", "o:"), ("ū", "u:"),
    ("ȫ", "O:"), ("ǖ", "U:"),
    ("ö", "O"), ("ü", "U"),
    ("γ", "G"),
    # ОСОБОЕ ПРАВИЛО: č перед i пишется другой буквой — ᡔ (U+1854), а не
    # ᡒ (U+1852), как во всех остальных позициях. То есть či -> ᡔᡅ.
    #
    # Здесь мы подменяем č на ASCII "c", который ниже как раз и ведёт в
    # ᡔ. Строка стоит ВЫШЕ общего правила для č, поэтому срабатывает
    # первой, а до неё долгие гласные уже превратились в "i:" — значит
    # čī к этому моменту выглядит как "či:" и подпадает под то же
    # правило автоматически. Так оба случая, и краткий и долгий,
    # обрабатываются одной строкой.
    ("či", "ci"),
    ("č", "C"),
    ("š", "S"),
    # ǰ — три записи, см. _J_INITIAL_BACK. Порядок важен: сначала ǰi, потом
    # начало слова, остальное — обычная ᡓ.
    ("ǰi", _JI_MARK + "i"),
    (_J_INITIAL_BACK, "J"),
    ("ǰ", "j"),
    # x и k ведут в одну и ту же букву тодо бичиг — ᡍ (U+184D).
    #
    # ВАЖНО, почему через служебный символ, а не через "h", как было
    # раньше. Ниже, в _rom_to_todo, сначала отрабатывает таблица
    # _REPLACEMENTS с двухбуквенными сочетаниями из JS-раскладки: lh, gh,
    # kh, ch, zh. Если x превратить в "h", то в слове bolxu возникает
    # последовательность "lh", и она схлопывается в отдельную букву ᡀ:
    # получалось ᡋᡆᡀᡇ вместо ᡋᡆᠯᡍᡇ. Так ломались все слова, где x или k
    # стоят после l или g, — 1391 слово из 25664 в словаре.
    #
    # Служебный символ \x01 ни с чем не сцепляется, поэтому до таблицы
    # диграфов доходит нетронутым, а в _CHAR_ROM_TO_TODO для него заведена
    # прямая запись в ᡍ. Настоящие lh/gh/kh в транслитерации проекта не
    # встречаются ни разу, так что терять нечего.
    (_K_BEFORE_BACK, _K_MARK),
    ("k", _H_MARK),
    ("x", _H_MARK),
    # дефис (граница суффикса) НЕ трогаем здесь — он проходит как есть
    # в _rom_to_todo, где уже есть готовое правило "-" -> NNBSP ( ).
]

# обратная схема (для todo_to_translit): здесь x и k разводим обратно —
# ASCII "k"/"x", которые вернёт _todo_to_rom, уже корректно расставлены
# по гласной, просто переносим их как есть в нашу транслитерацию.
_ROM_TO_TRANSLIT_MULTI = [
    # Обратная сторона правилаči -> ᡔᡅ. Раз ᡔ перед i теперь приходит и от
    # č, и от c, однозначно развернуть нельзя — выбираем то, что почти
    # всегда верно: в словаре проекта či встречается 882 раза, а ci — два
    # (cidi, xulaγayici). Стоит первой строкой, до превращения "i:" в "ī",
    # поэтому ловит и долгий вариант: "ci:" -> "či:" -> "čī".
    ("ci", "či"),
    ("O:", "ȫ"), ("U:", "ǖ"),
    ("a:", "ā"), ("e:", "ē"), ("i:", "ī"), ("o:", "ō"), ("u:", "ū"),
    ("O", "ö"), ("U", "ü"),
    ("G", "γ"),
    ("C", "č"),
    ("S", "š"),
    ("j", "ǰ"),  # обычная ᡓ всегда даёт "полную" форму ǰ, не голое j
    ("h", "x"),  # ASCII "h" — контекстный fallback JS, когда рядом с ᡍ нет
                 # явной гласной (например, конец слова). Вместо этого
                 # смотрим на гласную ГАРМОНИЮ ВСЕГО СЛОВА (см. ниже) —
                 # но если и это не помогло, по умолчанию x.
]


def translit_to_rom(text):
    text = unicodedata.normalize("NFC", text)
    for src, dst in _TRANSLIT_TO_ROM_MULTI:
        # элементом таблицы может быть и готовая регулярка — так записаны
        # правила, которым нужен взгляд на соседнюю букву
        if hasattr(src, "sub"):
            text = src.sub(dst, text)
        else:
            text = text.replace(src, dst)
    return text


_BACK_HARMONY_LETTERS = set("aāoōuū")   # гласные заднего ряда
_FRONT_HARMONY_LETTERS = set("eēiīöȫüǖ")  # гласные переднего ряда


def _word_harmony(word):
    """Гармония гласных всего слова — используется только как запасной
    вариант, когда рядом нет явной гласной."""
    for ch in word:
        if ch in _BACK_HARMONY_LETTERS:
            return "back"
        if ch in _FRONT_HARMONY_LETTERS:
            return "front"
    return "back"  # совсем без гласных — редкий случай, дефолт


def rom_to_translit(text, word_for_harmony=None):
    for src, dst in _ROM_TO_TRANSLIT_MULTI:
        if src == "h":
            continue  # обработаем отдельно, с учётом гармонии
        text = text.replace(src, dst)
    if "h" in text and word_for_harmony is not None:
        fallback = "k" if _word_harmony(word_for_harmony) == "front" else "x"
        text = text.replace("h", fallback)
    else:
        text = text.replace("h", "x")
    return unicodedata.normalize("NFC", text)


